const dicts: Record<Lang, Dictionary<RoomKey>> = { fr, en, de };

export const roomT = translator<RoomKey>(dicts);

/** Clé connue du dictionnaire du serveur (ex. clé composée à l'exécution). */
export function isRoomKey(key: string): key is RoomKey {
  return Object.prototype.hasOwnProperty.call(fr, key);
}

/** Texte à traduire, construit avec une clé vérifiée. */
export function roomText(key: RoomKey, params?: Params): I18nText {
  return params ? { key, params } : { key };
}

/** Rend un I18nText du serveur dans une langue. */
export function renderRoomText(lang: Lang, text: I18nText): string {
  return roomT(lang, text.key as RoomKey, text.params);
}

/**
 * Erreur traduisible : `message` en anglais (journaux, texte renvoyé au modèle),
 * `i18n` pour l'afficher dans la langue de chaque participant.
 */
export class I18nError extends Error {
  readonly i18n: I18nText;

  constructor(key: RoomKey, params?: Params) {
    super(roomT('en', key, params));
    this.name = 'I18nError';
    this.i18n = roomText(key, params);
  }

  /** Message dans une langue donnée. */
  in(lang: Lang): string {
    return renderRoomText(lang, this.i18n);
  }
}
