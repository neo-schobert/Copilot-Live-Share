export const extensionT = translator<ExtensionKey>({ fr, en, de });

/** Titre affiché d'une discussion : titre vide (aucune question encore) ou inconnu → « Nouvelle discussion ». */
export function conversationTitle(lang: Lang, title: string | undefined): string {
  return title || roomT(lang, 'conv.untitled');
}

/** Texte du serveur traduit dans la langue de l'extension, texte brut sinon. */
export function roomText(lang: Lang, text: I18nText | undefined, fallback: string): string {
  return text ? roomT(lang, text.key as RoomKey, text.params) : fallback;
}
